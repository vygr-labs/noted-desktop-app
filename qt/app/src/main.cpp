namespace {

QFile* g_log = nullptr;

void messageHandler(QtMsgType type, const QMessageLogContext&, const QString& msg)
{
    static const char* labels[] = {"DEBUG", "WARN ", "CRIT ", "FATAL", "INFO "};
    const QString line = QStringLiteral("[%1] %2 %3")
                             .arg(QDateTime::currentDateTime().toString(Qt::ISODateWithMs),
                                  QString::fromLatin1(labels[qBound(0, int(type), 4)]), msg);
    if (g_log && g_log->isOpen()) {
        QTextStream(g_log) << line << '\n';
        g_log->flush();
    }
    std::fprintf(stderr, "%s\n", qPrintable(line));
    if (type == QtFatalMsg) abort();
}

// The source checkout, when running from a build tree (qt/build/…).
QString repoRoot()
{
    QDir d(QCoreApplication::applicationDirPath());
    for (int hop = 0; hop < 5; ++hop) {
        if (d.exists(QStringLiteral("qt/CMakeLists.txt")) && d.exists(QStringLiteral("app"))) return d.absolutePath();
        if (!d.cdUp()) break;
    }
    return {};
}

void registerFonts()
{
    for (const char* f : {":/fonts/Geist-Variable.ttf", ":/fonts/GeistMono-Variable.ttf", ":/fonts/lucide.ttf"}) {
        const int id = QFontDatabase::addApplicationFont(QString::fromLatin1(f));
        if (id < 0) qWarning() << "failed to load font" << f;
        else qDebug() << "font" << f << QFontDatabase::applicationFontFamilies(id);
    }
    QFont ui;
    ui.setFamilies({QStringLiteral("Geist"), QStringLiteral("Segoe UI Variable Text"), QStringLiteral("Segoe UI"),
                    QStringLiteral(".AppleSystemUIFont"), QStringLiteral("Cantarell")});
    ui.setPixelSize(14);
    ui.setHintingPreference(QFont::PreferNoHinting);
    QGuiApplication::setFont(ui);
}

}  // namespace

int main(int argc, char* argv[])
{
    QGuiApplication::setOrganizationName(QStringLiteral("Voyager Technologies"));
    QGuiApplication::setOrganizationDomain(QStringLiteral("voyagerlabs.tech"));
    QGuiApplication::setApplicationName(QStringLiteral("noted"));
    QGuiApplication::setApplicationVersion(QStringLiteral(NOTED_VERSION_STRING));
    QQuickStyle::setStyle(QStringLiteral("Basic"));
    QGuiApplication app(argc, argv);
    QGuiApplication::setWindowIcon(QIcon(QStringLiteral(":/brand/icon.png")));

    QCommandLineParser cli;
    cli.setApplicationDescription(QStringLiteral("noted. — a minimal, distraction-free note-taking app"));
    cli.addHelpOption();
    cli.addVersionOption();
    QCommandLineOption dbOpt(QStringLiteral("db"), QStringLiteral("Use this database file."), QStringLiteral("path"));
    QCommandLineOption realDataOpt(QStringLiteral("real-data"), QStringLiteral("In a dev build, use the real per-user database."));
    QCommandLineOption shotOpt(QStringLiteral("screenshot"), QStringLiteral("Save a window screenshot and quit."), QStringLiteral("png"));
    QCommandLineOption delayOpt(QStringLiteral("screenshot-delay"), QStringLiteral("Delay before the screenshot (ms)."), QStringLiteral("ms"), QStringLiteral("1500"));
    QCommandLineOption stateOpt(QStringLiteral("state"), QStringLiteral("Startup UI state as JSON (dev/testing)."), QStringLiteral("json"));
    QCommandLineOption quickOpt(QStringLiteral("quick-capture"), QStringLiteral("Open the quick capture window."));
    cli.addOptions({dbOpt, realDataOpt, shotOpt, delayOpt, stateOpt, quickOpt});
    cli.addPositionalArgument(QStringLiteral("files"), QStringLiteral("Markdown or text files to open as notes."), QStringLiteral("[files...]"));
    cli.process(app);

    // ── logging ──────────────────────────────────────────────────────────
    const QString repo = repoRoot();
    const QString logDir = !repo.isEmpty() ? repo + QStringLiteral("/personal")
                                           : QStandardPaths::writableLocation(QStandardPaths::AppDataLocation);
    QDir().mkpath(logDir);
    g_log = new QFile(logDir + QStringLiteral("/noted-qt.log"));
    (void)g_log->open(QIODevice::WriteOnly | QIODevice::Append | QIODevice::Text);
    qInstallMessageHandler(messageHandler);

    // ── data location ────────────────────────────────────────────────────
    // A dev build never touches the real database unless told to: it works
    // on personal/qt-data/app.sqlite, seeded once from a snapshot of it.
    QString dbPath = cli.value(dbOpt);
    if (dbPath.isEmpty()) dbPath = qEnvironmentVariable("NOTED_DB");
    bool devData = false;
    if (dbPath.isEmpty() && !repo.isEmpty() && !cli.isSet(realDataOpt)) {
        dbPath = repo + QStringLiteral("/personal/qt-data/app.sqlite");
        devData = true;
        if (noted::Database::snapshot(noted::Database::defaultPath(), dbPath))
            qInfo() << "seeded dev database from" << noted::Database::defaultPath();
    }
    if (dbPath.isEmpty()) dbPath = noted::Database::defaultPath();

    registerFonts();

    std::unique_ptr<noted::Database> database;
    try {
        database = std::make_unique<noted::Database>(dbPath);
    } catch (const std::exception& e) {
        qCritical() << "could not open database" << dbPath << e.what();
        return 1;
    }
    qInfo().noquote() << "noted" << NOTED_VERSION_STRING << "db:" << dbPath << (devData ? "(dev copy)" : "");

    noted::NoteStore store(*database);
    noted::NotesModel notes(store);
    noted::DateText dates;
    AppController controller(store, dbPath, devData);
    OpenFiles files(store);

    const bool takeShot = cli.isSet(shotOpt);
    if (!takeShot && !controller.claimSingleInstance(cli.positionalArguments())) {
        qInfo() << "handed off to the running instance";
        return 0;
    }
    database->startWatching();

    QQmlApplicationEngine engine;
    qml_register_types_Noted();
    qmlRegisterSingletonInstance("Noted", 1, 0, "Store", &store);
    qmlRegisterSingletonInstance("Noted", 1, 0, "Notes", &notes);
    qmlRegisterSingletonInstance("Noted", 1, 0, "Dates", &dates);
    qmlRegisterSingletonInstance("Noted", 1, 0, "App", &controller);
    qmlRegisterSingletonInstance("Noted", 1, 0, "Files", &files);
    engine.rootContext()->setContextProperty(QStringLiteral("startupState"), cli.value(stateOpt));
    engine.rootContext()->setContextProperty(QStringLiteral("startupFiles"), cli.positionalArguments());
    engine.rootContext()->setContextProperty(QStringLiteral("startupQuickCapture"), cli.isSet(quickOpt));
    engine.rootContext()->setContextProperty(QStringLiteral("screenshotMode"), takeShot);

    QObject::connect(&engine, &QQmlApplicationEngine::objectCreationFailed, &app, [] { QCoreApplication::exit(1); },
                     Qt::QueuedConnection);
    engine.loadFromModule("Noted", "Main");
    if (engine.rootObjects().isEmpty()) return 1;

    auto* window = qobject_cast<QQuickWindow*>(engine.rootObjects().constFirst());
    if (window) noted::installNativeWindowChrome(window);
    if (!takeShot) controller.registerQuickCaptureHotkey();

    if (takeShot && window) {
        // Out of the way: on the smallest screen (a laptop's own panel, not the
        // monitor someone is watching) and without taking focus.
        QScreen* target = window->screen();
        for (QScreen* s : QGuiApplication::screens()) {
            const QSizeF a = s->physicalSize(), b = target->physicalSize();
            if (a.width() * a.height() < b.width() * b.height()) target = s;
        }
        window->setScreen(target);
        window->setPosition(target->availableGeometry().topLeft());
        window->show();
        const QString out = cli.value(shotOpt);
        QTimer::singleShot(cli.value(delayOpt).toInt(), window, [window, out] {
            const QImage img = window->grabWindow();
            img.save(out);
            qInfo() << "screenshot saved to" << out << img.size();
            QCoreApplication::quit();
        });
    }

    const int rc = QGuiApplication::exec();
    return rc;
}
